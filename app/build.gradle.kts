  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.aistudio.bebasbrowser.skyxqa"
    minSdk = 24
    targetSdk = 36
    versionCode = 2
    versionName = "1.0.1"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

    val dotEnvText = providers
      .fileContents(rootProject.layout.projectDirectory.file(".env"))
      .asText
      .orNull
      .orEmpty()
    val dotEnvProps = Properties().apply {
      if (dotEnvText.isNotEmpty()) load(dotEnvText.reader())
    }
    val rawXingchiKey = providers.environmentVariable("XINGCHI_API_KEY").orNull?.trim().orEmpty()
      .ifEmpty { dotEnvProps.getProperty("XINGCHI_API_KEY")?.trim().orEmpty() }

    val vaultSeed = SecureRandom()
    val shardA = ByteArray(32).also { vaultSeed.nextBytes(it) }
    val shardB = ByteArray(32).also { vaultSeed.nextBytes(it) }
    val combined = ByteArray(32) { i -> (shardA[i].toInt() xor shardB[i].toInt()).toByte() }
    val aesKeyBytes = MessageDigest.getInstance("SHA-256").run {
      update(combined)
      update("StayFlow::Sky::KeyVault::v1".toByteArray(Charsets.UTF_8))
      digest()
    }
    val iv = ByteArray(12).also { vaultSeed.nextBytes(it) }
    val cipherBytes = Cipher.getInstance("AES/GCM/NoPadding").run {
      init(Cipher.ENCRYPT_MODE, SecretKeySpec(aesKeyBytes, "AES"), GCMParameterSpec(128, iv))
      doFinal(rawXingchiKey.toByteArray(Charsets.UTF_8))
    }
    fun ByteArray.toHex(): String = joinToString("") { "%02x".format(it) }

    buildConfigField("String", "VAULT_CIPHER_HEX", "\"${cipherBytes.toHex()}\"")
    buildConfigField("String", "VAULT_IV_HEX", "\"${iv.toHex()}\"")
    buildConfigField("String", "VAULT_SHARD_A_HEX", "\"${shardA.toHex()}\"")
    buildConfigField("String", "VAULT_SHARD_B_HEX", "\"${shardB.toHex()}\"")
  }

  // Do not remove or modify these signingConfigs. They are necessary for building, installing,
